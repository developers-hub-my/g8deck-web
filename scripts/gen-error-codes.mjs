/**
 * Generates the public error-code page (src/docs/error-codes.md) from the
 * G8Deck application's registry, so the page cannot drift from the codes the
 * console actually shows.
 *
 *   node scripts/gen-error-codes.mjs [path/to/g8deck-app]
 *
 * The app path defaults to $G8DECK_APP, then to ../g8deck-app. It runs
 * `php artisan docs:error-codes --format=json` there, so the app must boot
 * (vendor installed, an .env with an APP_KEY). Output is committed.
 */
import { writeFileSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const app = resolve(process.argv[2] ?? process.env.G8DECK_APP ?? join(root, '..', 'g8deck-app'));

if (!existsSync(join(app, 'artisan'))) {
    console.error(`No G8Deck app at ${app} — pass its path as the first argument.`);
    process.exit(1);
}

const { codes } = JSON.parse(
    execFileSync('php', ['artisan', 'docs:error-codes', '--format=json'], {
        cwd: app,
        encoding: 'utf8',
    })
);

if (!Array.isArray(codes) || codes.length === 0) {
    console.error('docs:error-codes returned no codes — refusing to write an empty page.');
    process.exit(1);
}

const today = new Date().toISOString().slice(0, 10);

const sections = codes.map((c) =>
    [
        `## ${c.code}`,
        '',
        `**${c.title}.** ${c.meaning}`,
        '',
        '**What you can do**',
        '',
        ...c.what_you_can_do.map((step, i) => `${i + 1}. ${step}`),
        '',
        `**When to contact support:** ${c.contact_support}`,
    ].join('\n')
);

const index = [
    '| Code | What it means |',
    '| ---- | ------------- |',
    ...codes.map((c) => `| [${c.code}](#${c.code.toLowerCase()}) | ${c.title} |`),
].join('\n');

const page = `---
title: Error codes
description: 'What each G8Deck error code means, what you can do about it, and when to contact support — with the reference that lets support find your incident.'
section: help
order: 15
updated: ${today}
generated: true
---

<!-- GENERATED by scripts/gen-error-codes.mjs from the G8Deck application (php artisan docs:error-codes). Do not edit by hand: re-run \`node scripts/gen-error-codes.mjs\`. -->

When something G8Deck does fails, the console tells you in plain words and
ends the message with two short labels:

\`\`\`
Your server refused G8Deck's login. Code G8-E202 · Reference 7K2-QX9
\`\`\`

- The **code** (\`G8-E202\`) says what kind of failure it was. It is the same
  every time that kind of failure happens, and it is what you look up on this
  page.
- The **reference** (\`7K2-QX9\`) belongs to this one incident. Give it to
  support and they can find the technical detail behind the message. The
  reference itself contains no data, and support can only look it up for your
  own organisation.

Codes are never reused and never renumbered, so a code you wrote down last
year still means the same thing. If you see a code that is not listed here,
your console is newer than this page — contact support with the code and the
reference.

${index}

${sections.join('\n\n')}
`;

writeFileSync(join(root, 'src', 'docs', 'error-codes.md'), page);
console.log(`Wrote src/docs/error-codes.md (${codes.length} codes).`);
